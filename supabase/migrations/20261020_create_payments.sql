
CREATE TABLE public.payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    sale_transaction_id bigint NOT NULL
        REFERENCES public.sale_transactions(id),

    amount numeric(12,2) NOT NULL
        CHECK (amount > 0),

    payment_type text NOT NULL DEFAULT 'payment'
        CHECK (payment_type IN ('payment', 'refund')),

    payment_method text NOT NULL DEFAULT 'other'
        CHECK (
            payment_method IN (
                'cash',
                'bank_transfer',
                'card',
                'other'
            )
        ),

    paid_at timestamptz NOT NULL DEFAULT now(),

    notes text,

    created_at timestamptz NOT NULL DEFAULT now()
);

-- Speed up loading payments for a transaction.
CREATE INDEX payments_transaction_idx
ON public.payments (sale_transaction_id);

-- Speed up chronological payment reporting.
CREATE INDEX payments_paid_at_idx
ON public.payments (paid_at DESC);

-- Restrict access to authorised business members.
ALTER TABLE public.payments ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Members can manage payments"
ON public.payments
FOR ALL
TO authenticated
USING (public.is_business_member())
WITH CHECK (public.is_business_member());

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.payments TO authenticated;

GRANT USAGE, SELECT
ON SEQUENCE public.payments_id_seq TO authenticated;
