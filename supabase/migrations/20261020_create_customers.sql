
-- M1: Sales Architecture
-- Create optional customer records for RM&CO.

CREATE TABLE public.customers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name text NOT NULL,
    instagram_handle text,
    snapchat_handle text,
    phone text,
    notes text,

    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT customers_name_not_blank
        CHECK (length(btrim(name)) > 0)
);

-- Enable Row Level Security.
ALTER TABLE public.customers ENABLE ROW LEVEL SECURITY;

-- Only authorised business members can access customer records.
CREATE POLICY "Members can manage customers"
ON public.customers
FOR ALL
TO authenticated
USING ((SELECT public.is_business_member()))
WITH CHECK ((SELECT public.is_business_member()));

-- Restrict API access to authenticated users.
REVOKE ALL ON TABLE public.customers FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE
ON TABLE public.customers TO authenticated;

GRANT USAGE, SELECT
ON SEQUENCE public.customers_id_seq TO authenticated;
