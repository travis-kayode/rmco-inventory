
-- M1: Sales Architecture
-- A transaction groups one or more sold items.

CREATE TABLE public.sale_transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Customer details are optional.
    customer_id bigint
        REFERENCES public.customers(id)
        ON DELETE SET NULL,

    -- A transaction starts as a draft.
    status text NOT NULL DEFAULT 'draft',

    -- Optional internal notes.
    notes text,

    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    completed_at timestamptz,

    CONSTRAINT sale_transactions_valid_status
        CHECK (status IN (
            'draft',
            'pending',
            'completed',
            'cancelled'
        )),

    CONSTRAINT sale_transactions_completion_check
        CHECK (
            (status = 'completed' AND completed_at IS NOT NULL)
            OR
            (status <> 'completed' AND completed_at IS NULL)
        )
);

-- Enable Row Level Security.
ALTER TABLE public.sale_transactions
ENABLE ROW LEVEL SECURITY;

-- Only authorised business members can manage transactions.
CREATE POLICY "Members can manage transactions"
ON public.sale_transactions
FOR ALL
TO authenticated
USING ((SELECT public.is_business_member()))
WITH CHECK ((SELECT public.is_business_member()));

REVOKE ALL ON TABLE public.sale_transactions FROM anon;

GRANT SELECT, INSERT, UPDATE, DELETE
ON TABLE public.sale_transactions TO authenticated;

GRANT USAGE, SELECT
ON SEQUENCE public.sale_transactions_id_seq
TO authenticated;

-- Useful when displaying recent transactions.
CREATE INDEX sale_transactions_created_at_idx
ON public.sale_transactions (created_at DESC);

-- Useful for customer purchase history.
CREATE INDEX sale_transactions_customer_id_idx
ON public.sale_transactions (customer_id);
