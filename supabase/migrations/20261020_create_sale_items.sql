
-- Each row represents one physical item in a sale cart.
CREATE TABLE public.sale_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    sale_transaction_id bigint NOT NULL
        REFERENCES public.sale_transactions(id)
        ON DELETE CASCADE,

    inventory_item_id bigint
        REFERENCES public.inventory_items(id),

    sourcing_request_id bigint
        REFERENCES public.sourcing_requests(id),

    sale_price numeric(12,2) NOT NULL
        CHECK (sale_price >= 0),

    cost_snapshot numeric(12,2)
        CHECK (cost_snapshot >= 0),

    created_at timestamptz NOT NULL DEFAULT now(),

    -- A sale item must reference stock OR sourcing,
    -- never both and never neither.
    CONSTRAINT sale_items_one_source CHECK (
        (inventory_item_id IS NOT NULL)
        <>
        (sourcing_request_id IS NOT NULL)
    )
);

-- Prevent adding the same item twice to the SAME cart.
-- The same item can still appear in different draft carts.
CREATE UNIQUE INDEX sale_items_unique_stock_per_cart
ON public.sale_items (
    sale_transaction_id,
    inventory_item_id
)
WHERE inventory_item_id IS NOT NULL;

CREATE UNIQUE INDEX sale_items_unique_sourcing_per_cart
ON public.sale_items (
    sale_transaction_id,
    sourcing_request_id
)
WHERE sourcing_request_id IS NOT NULL;

-- Speed up queries that load a cart's items.
CREATE INDEX sale_items_transaction_idx
ON public.sale_items (sale_transaction_id);

CREATE INDEX sale_items_inventory_idx
ON public.sale_items (inventory_item_id)
WHERE inventory_item_id IS NOT NULL;

CREATE INDEX sale_items_sourcing_idx
ON public.sale_items (sourcing_request_id)
WHERE sourcing_request_id IS NOT NULL;

-- Restrict access to authorised RM&CO members.
ALTER TABLE public.sale_items ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Members can manage sale items"
ON public.sale_items
FOR ALL
TO authenticated
USING (public.is_business_member())
WITH CHECK (public.is_business_member());

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.sale_items TO authenticated;

GRANT USAGE, SELECT
ON SEQUENCE public.sale_items_id_seq TO authenticated;
