
-- M1: Sales Architecture
-- Track customer-led sourcing requests.

CREATE TABLE public.sourcing_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Customer may be unknown or not recorded.
    customer_id bigint
        REFERENCES public.customers(id)
        ON DELETE SET NULL,

    -- Optional link to an existing product.
    product_id bigint
        REFERENCES public.products(id)
        ON DELETE SET NULL,

    -- Product details captured independently,
    -- even when the product isn't in inventory.
    brand text NOT NULL DEFAULT '',
    item_name text NOT NULL,
    colourway text NOT NULL DEFAULT '',
    size text,
    condition text,

    -- Financial information.
    agreed_price numeric(12, 2),
    sourcing_cost numeric(12, 2),

    -- Track progress independently from payment.
    status text NOT NULL DEFAULT 'requested',

    notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    secured_at timestamptz,
    completed_at timestamptz,

    CONSTRAINT sourcing_item_name_not_blank
        CHECK (length(btrim(item_name)) > 0),

    CONSTRAINT sourcing_valid_condition
        CHECK (
            condition IS NULL
            OR condition IN ('DS', 'Used')
        ),

    CONSTRAINT sourcing_valid_status
        CHECK (
            status IN (
                'requested',
                'sourcing',
                'secured',
                'completed',
                'cancelled'
            )
        ),

    CONSTRAINT sourcing_agreed_price_nonnegative
        CHECK (agreed_price IS NULL OR agreed_price >= 0),

    CONSTRAINT sourcing_cost_nonnegative
        CHECK (sourcing_cost IS NULL OR sourcing_cost >= 0)
);

-- Indexes for sourcing history and active requests.
CREATE INDEX sourcing_requests_customer_id_idx
ON public.sourcing_requests (customer_id);

CREATE INDEX sourcing_requests_status_idx
ON public.sourcing_requests (status);

CREATE INDEX sourcing_requests_created_at_idx
ON public.sourcing_requests (created_at DESC);

-- Enable Row Level Security.
ALTER TABLE public.sourcing_requests
ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Members can manage sourcing requests"
ON public.sourcing_requests
FOR ALL
TO authenticated
USING ((SELECT public.is_business_member()))
WITH CHECK ((SELECT public.is_business_member()));

-- API permissions.
REVOKE ALL ON TABLE public.sourcing_requests FROM anon;

GRANT SELECT, INSERT, UPDATE, DELETE
ON TABLE public.sourcing_requests TO authenticated;

GRANT USAGE, SELECT
ON SEQUENCE public.sourcing_requests_id_seq
TO authenticated;
